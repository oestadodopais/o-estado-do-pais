import assert from 'node:assert/strict';
import fs from 'node:fs';
import {load} from 'js-yaml';
import {dataDaCasa} from '../../src/lib/datas.mjs';
import {dataDaSinopse} from '../../scripts/voz-pais.mjs';
const id='flexibilizacao-regras-2018';
const data=load(fs.readFileSync(`ledger/claims/${id}.yml`,'utf8'));
const ano=load(fs.readFileSync(`ledger/claims/${id}-ano.yml`,'utf8'));
assert.equal(data.unit,'data');
assert.equal(data.value,'31 de dezembro de 2018');
assert.equal(data.reference_date,'2018-12-31');
assert.ok(data.excerpt.includes(data.value));
assert.equal(ano.value.replace(/\s/g,''),data.reference_date.slice(0,4));
assert.equal(ano.document.source_sha256,data.document.source_sha256);
const texto=fs.readFileSync('studies-src/penalizacoes-por-reforma-antecipada-2026/pt.html','utf8');
assert.ok(texto.includes(data.value));
const cartao=fs.readFileSync('src/data/leituras.mjs','utf8');
const referencias=[...cartao.matchAll(/\{"data": \{"id": "flexibilizacao-regras-2018", "campo": "reference_date", "valor": "([^"]+)"\}\}/g)];
assert.equal(referencias.length,4);
for(const [,valor] of referencias) assert.equal(valor,data.reference_date);
assert.equal(dataDaCasa(data.reference_date,'pt'),'31.12.2018');
assert.equal(dataDaCasa(data.reference_date,'en'),'31.12.2018');
const parte={data:{id,campo:'reference_date',valor:data.reference_date}};
assert.equal(dataDaSinopse(parte),'31.12.2018');
assert.equal(dataDaSinopse({data:{...parte.data,valor:'2019-12-31'}}),null);
assert.equal(dataDaSinopse({data:{...parte.data,campo:'access_date'}}),null);
console.log('COR3 reforma: data e ano ligados ao mesmo documento; quatro referências dos cartões; texto do estudo conservado.');
